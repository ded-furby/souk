// Desert look upgrade. Called once after every area is built, with the desert area object returned by its builder
// ({ id, group, env, lights, update, ... }). Owned by the desert-look work; mutate materials / env / add detail here.
// ctx: { M (game materials), renderer, scene, quality, G (game context) }
//
// What this does (nothing is added to the story — same dunes, same ruins, same sun direction, terrain heights untouched):
//   sand        wind ripples + grain + broad colour drift, mapped in world space so nothing visibly tiles
//   atmosphere  a golden-hour sky dome and matching aerial perspective, only while the player is in the desert
//   light       desert env values (area.env) — warm key, cool sky fill, warm bounce
//   ruins       desert copies of the stone materials: sand banked at the base, dust on ledges, contact shade, same haze
// Textures are generated by tools/desert/textures.py into assets/desert/. Nothing here animates, so nothing can flicker.
import { BackSide, BufferAttribute, Color, Mesh, NoColorSpace, RepeatWrapping, ShaderMaterial, SphereGeometry, TextureLoader, Vector2, Vector3, Vector4 } from "three";

const hex = (h, k = 1) => new Color(h).multiplyScalar(k);

// Shared by the sky dome and every desert material, so the far dunes dissolve into exactly the sky behind them.
const U = {
  dSun: { value: new Vector3(0.46, 0.27, -0.85).normalize() },
  dHzWarm: { value: hex("#ffd9a6", 1.1) }, // horizon haze under the sun
  dHzCool: { value: hex("#e8c5ae", 0.85) }, // horizon haze opposite the sun
  dGlow: { value: hex("#ffa858", 0.4) }, // forward-scatter glow around the sun's bearing
  dFog: { value: new Vector4(1 / 360, 1 / 38, 2, 0.97) }, // 1/visibility, 1/haze-layer thickness, layer base y, cap
  dWind: { value: new Vector2(-0.94, 0.34).normalize() }, // ground direction the wind blows toward; ripple crests run across it
  dRipple: { value: null },
  dGrain: { value: null },
  dMacro: { value: null },
  dSandA: { value: hex("#b97f4a") }, // deeper, redder sand
  dSandB: { value: hex("#d8a96f") }, // paler, finer sand
  dSheen: { value: 0.55 },
};

const ATMOS = /* glsl */ `
uniform vec3 dSun, dHzWarm, dHzCool, dGlow;
uniform vec4 dFog;
vec3 dHaze(vec3 dir) {
  float w = 0.5 + 0.5 * dot(normalize(dir.xz), normalize(dSun.xz));
  return mix(dHzCool, dHzWarm, w * w) + dGlow * pow(w, 12.0);
}
vec3 dAerial(vec3 col, vec3 wp) {
  vec3 v = wp - cameraPosition;
  float d = length(v), t = d * dFog.x;
  float lift = max(0.5 * (wp.y + cameraPosition.y) - dFog.z, 0.0) * dFog.y; // crests clear the haze layer sooner than hollows
  return mix(col, dHaze(v), (1.0 - exp(-t * t * exp(-lift))) * dFog.w);
}`;

const PARS = /* glsl */ `
varying vec3 dWorld;
uniform sampler2D dRipple, dGrain, dMacro;
uniform vec2 dWind;
uniform vec3 dSandA, dSandB;
uniform float dSheen;
${ATMOS}`;

const SAND = /* glsl */ `
{
  vec2 wp = dWorld.xz;
  float dist = length(vViewPosition);
  vec2 q = vec2(dot(wp, dWind), dot(wp, vec2(-dWind.y, dWind.x))); // x down-wind, y along the ripple crests
  vec3 mac = texture2D(dMacro, q * 0.0061).rgb; // ~165 m drift + wind streaks
  vec3 nW = normalize((vec4(normal, 0.0) * viewMatrix).xyz);
  float calm = smoothstep(0.80, 0.94, nW.y); // slip faces are too steep to hold ripples
  #ifdef D_LOW
    vec2 qw = q;
    float mid = 0.5;
  #else
    vec3 m2 = texture2D(dMacro, q.yx * 0.027 + 0.37).rgb; // ~37 m
    vec2 qw = q + (m2.rb - 0.5) * 1.4; // meander, so ripple lines never run ruler-straight
    float mid = m2.g;
  #endif
  vec4 r1 = texture2D(dRipple, qw / 5.6);
  float k1 = calm * (1.0 - smoothstep(14.0, 55.0, dist)) * (0.45 + 0.7 * mac.b); // fades out with distance: no moiré, no shimmer
  vec2 bump = (r1.xy * 2.0 - 1.0) * k1;
  float grain = 0.5, kg = 0.0;
  #ifndef D_LOW
    const float c = 0.966, s = 0.259;
    vec2 n2 = texture2D(dRipple, vec2(c * qw.x - s * qw.y, s * qw.x + c * qw.y) / 19.0 + 0.5).xy * 2.0 - 1.0; // broad sand waves
    bump += vec2(c * n2.x + s * n2.y, c * n2.y - s * n2.x) * calm * (1.0 - smoothstep(60.0, 160.0, dist)) * 0.35;
    vec3 g = texture2D(dGrain, wp * 2.7).rgb;
    kg = 1.0 - smoothstep(2.5, 11.0, dist);
    bump += (g.xy * 2.0 - 1.0) * kg * 0.45;
    grain = g.z;
  #endif
  vec3 w3 = vec3(dWind.x, 0.0, dWind.y);
  vec3 t1 = normalize(w3 - nW * dot(nW, w3));
  normal = normalize((viewMatrix * vec4(normalize(nW + t1 * bump.x + cross(t1, nW) * bump.y), 0.0)).xyz);

  float rh = mix(0.5, r1.z, k1); // ripple height: crests carry the fine pale grains
  vec3 sand = mix(dSandA, dSandB, smoothstep(0.2, 0.8, mac.r) * 0.75 + (mac.g - 0.5) * 0.5);
  sand *= (0.9 + 0.2 * mid) * (0.9 + 0.2 * rh) * mix(1.0, 0.8 + 0.4 * grain, kg);
  diffuseColor.rgb = sand;
  roughnessFactor = 0.9 - 0.14 * rh * k1;
}`;

// Ruins: dH is the height of each vertex above the sand under it.
const RUIN = /* glsl */ `
#include <normal_fragment_maps>
{
  float up = normalize((vec4(normal, 0.0) * viewMatrix).xyz).y;
  float n = texture2D(dMacro, dWorld.xz * 0.19 + dWorld.y * 0.11).r;
  float drift = 1.0 - smoothstep(0.03, 0.22 + 0.5 * n, vDH); // sand banked against the base
  drift = max(drift, smoothstep(0.55, 0.95, up) * (0.3 + 0.5 * n) * (1.0 - smoothstep(0.4, 3.5, vDH))); // dust settled on ledges
  diffuseColor.rgb = mix(diffuseColor.rgb, mix(dSandA, dSandB, 0.55), drift * 0.85);
  roughnessFactor = mix(roughnessFactor, 0.92, drift);
  dShade = 0.68 + 0.32 * smoothstep(0.0, 0.5, vDH); // contact shade where stone meets sand
}`;

function patch(m, { surface, ruin, key }) {
  m.fog = false; // replaced by dAerial
  m.onBeforeCompile = (s) => {
    for (const k of Object.keys(U)) s.uniforms[k] = U[k];
    s.vertexShader = s.vertexShader
      .replace("#include <common>", "#include <common>\nvarying vec3 dWorld;" + (ruin ? "\nattribute float dH; varying float vDH;" : ""))
      .replace("#include <worldpos_vertex>", "#include <worldpos_vertex>\ndWorld = (modelMatrix * vec4(transformed, 1.0)).xyz;" + (ruin ? "\nvDH = dH;" : ""));
    s.fragmentShader = s.fragmentShader
      .replace("#include <common>", "#include <common>\n" + PARS + (ruin ? "\nvarying float vDH; float dShade = 1.0;" : ""))
      .replace("#include <normal_fragment_maps>", surface)
      .replace("#include <lights_fragment_end>", "#include <lights_fragment_end>\n" + (ruin ? "reflectedLight.indirectDiffuse *= dShade; reflectedLight.directDiffuse *= 0.5 + 0.5 * dShade;" : "reflectedLight.directSpecular *= dSheen;"))
      .replace("#include <opaque_fragment>", "#include <opaque_fragment>\ngl_FragColor.rgb = dAerial(gl_FragColor.rgb, dWorld);");
  };
  m.customProgramCacheKey = () => key;
  return m;
}

function sandMaterial(base, low) {
  const m = base.clone();
  m.name = "desertSand";
  m.map = m.normalMap = m.roughnessMap = null;
  m.color.set("#ffffff");
  m.vertexColors = false;
  if (low) m.defines = { ...m.defines, D_LOW: 1 };
  return patch(m, { surface: SAND, key: "desert-sand" + (low ? "-low" : "") });
}

function skyDome() {
  const mat = new ShaderMaterial({
    uniforms: { ...U, dZenith: { value: hex("#2d6cb8") }, dSkyMid: { value: hex("#9cc0e0") }, dK: { value: new Vector4(1.1, 0.4, 0.14, 11) }, dFade: { value: 0 } },
    side: BackSide,
    depthWrite: false,
    transparent: true,
    fog: false,
    vertexShader: /* glsl */ `varying vec3 vDir; void main(){ vDir = position; vec4 p = projectionMatrix * modelViewMatrix * vec4(position, 1.0); gl_Position = p.xyww; }`,
    fragmentShader: /* glsl */ `varying vec3 vDir; uniform vec3 dZenith, dSkyMid; uniform vec4 dK; uniform float dFade;
      ${ATMOS}
      void main(){
        vec3 d = normalize(vDir);
        float up = clamp(d.y, 0.0, 1.0);
        vec3 col = mix(dHaze(d), dSkyMid, 1.0 - exp(-up * 6.5)); // the haze layer thins quickly above the horizon
        col = mix(col, dZenith, smoothstep(0.04, 0.8, up));
        float a = sqrt(max(2.0 - 2.0 * dot(d, dSun), 0.0)); // angle from the sun, radians
        col += vec3(1.0, 0.78, 0.5) * (exp(-a * 22.0) * dK.x + exp(-a * 6.0) * dK.y + exp(-a * 2.0) * dK.z) * (0.35 + 0.65 * smoothstep(-0.03, 0.08, d.y));
        col += vec3(1.0, 0.93, 0.8) * smoothstep(0.0135, 0.0095, a) * dK.w; // the disc itself
        gl_FragColor = vec4(col, dFade);
        #include <tonemapping_fragment>
        #include <colorspace_fragment>
      }`,
  });
  const mesh = new Mesh(new SphereGeometry(430, 48, 24), mat);
  mesh.name = "DesertSky";
  mesh.renderOrder = -9; // first of the transparents; depth-tested at the far plane, so it only fills sky pixels
  mesh.frustumCulled = false;
  mesh.userData.dynamic = true;
  return mesh;
}

// Height of the sand under (x, z), read back from the terrain mesh the builder made (a regular grid), so it can't drift from it.
function groundSampler(terrain) {
  const pos = terrain.geometry.attributes.position, n = Math.round(Math.sqrt(pos.count)) - 1;
  const x0 = pos.getX(0), z0 = pos.getZ(0), dx = (pos.getX(pos.count - 1) - x0) / n, dz = (pos.getZ(pos.count - 1) - z0) / n;
  return (x, z) => {
    const fx = (x - x0) / dx, fz = (z - z0) / dz;
    if (fx < 0 || fz < 0 || fx > n || fz > n) return 0; // the city side is paved at y = 0
    const ix = Math.min(n - 1, Math.floor(fx)), iz = Math.min(n - 1, Math.floor(fz)), tx = fx - ix, tz = fz - iz, i = iz * (n + 1) + ix;
    return (pos.getY(i) * (1 - tx) + pos.getY(i + 1) * tx) * (1 - tz) + (pos.getY(i + n + 1) * (1 - tx) + pos.getY(i + n + 2) * tx) * tz;
  };
}

export function upgradeDesert(area, { M, quality, G }) {
  const low = quality === "low";
  const tex = (name) =>
    new TextureLoader().loadAsync(`${G.base}assets/desert/${name}`).then((t) => {
      t.wrapS = t.wrapT = RepeatWrapping;
      t.colorSpace = NoColorSpace;
      t.flipY = false;
      t.anisotropy = low ? 2 : 8;
      return t;
    });
  // Everything is applied in one go once the textures are in, so the desert is never seen half-dressed.
  Promise.all([tex("ripple.jpg"), tex("grain.jpg"), tex("macro.jpg")])
    .then(([ripple, grain, macro]) => {
      U.dRipple.value = ripple;
      U.dGrain.value = grain;
      U.dMacro.value = macro;

      const sand = sandMaterial(M.sand, low);
      const ground = groundSampler(area.terrain);
      const ruins = new Map(); // game stone material -> its desert copy
      area.group.traverse((o) => {
        if (!o.isMesh) return;
        if (o === area.terrain || o.material === M.sand) o.material = sand;
        else if ([M.stone, M.stoneDark, M.plaster, M.carved].includes(o.material)) {
          const p = o.geometry.attributes.position, h = new Float32Array(p.count);
          for (let i = 0; i < p.count; i++) h[i] = p.getY(i) - ground(p.getX(i), p.getZ(i)); // static meshes are baked in world space
          o.geometry.setAttribute("dH", new BufferAttribute(h, 1));
          if (!ruins.has(o.material)) ruins.set(o.material, patch(o.material.clone(), { surface: RUIN, ruin: true, key: "desert-ruin" }));
          o.material = ruins.get(o.material);
        }
      });

      // Golden hour: warm low key, cool sky fill, bounce from the sand. Same sun direction as before.
      const env = area.env;
      Object.assign(env, { sun: 4.2, sunColor: "#ffc98f", hemi: 0.7, sky: "#a9bfe0", groundCol: "#c98d55", env: 0.42, fog: "#e6c49c", fogNear: 70, fogFar: 900, exposure: 0.95, zenith: "#5d86a8", horizon: "#f2c894", clouds: 0 });
      U.dSun.value.fromArray(env.sunDir).normalize();

      const sky = skyDome();
      area.group.add(sky);
      area.look = { U, sky, sand }; // handle for live tuning (tools/desert/tune.mjs)
      const update = area.update;
      area.update = (t, dt, p) => {
        update.call(area, t, dt, p);
        // fade in while walking out through the city gate (z -161 → -169); stateless, so chapter jumps can't strand it
        const k = Math.min(1, Math.max(0, (-161 - p.z) / 8));
        sky.visible = k > 0.002;
        sky.material.uniforms.dFade.value = k * k * (3 - 2 * k);
        sky.position.copy(p);
      };
    })
    .catch((e) => console.warn("desert look: keeping the original desert —", e));
}
